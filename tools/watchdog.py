"""
Finance Shorts Pro - Watchdog Monitor.
Runs daily at 17:00 UTC (22:30 IST) to verify that no scheduled topics are more than 3 hours
overdue while still in 'Pending' status. Catches dropped or skipped GitHub Actions scheduled runs.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timedelta
from pathlib import Path
from zoneinfo import ZoneInfo

# Add repo root to path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import config
from storage import state_store

IST = ZoneInfo("Asia/Kolkata")


def find_overdue_rows(
    now: datetime | None = None,
    state_file: Path | None = None,
    threshold_hours: float = 3.0,
) -> list[dict]:
    """
    Finds rows in state_store that are Pending, scheduled_at <= now - threshold_hours,
    and attempts < 2.
    """
    now_dt = now or datetime.now(IST)
    if now_dt.tzinfo is None:
        now_dt = now_dt.replace(tzinfo=IST)

    threshold_dt = now_dt - timedelta(hours=threshold_hours)
    st = state_store.load(state_file=state_file)
    rows = st.get("rows", {})

    overdue = []
    for rk, r in rows.items():
        if r.get("status") == "Pending" and r.get("attempts", 0) < 2:
            sched_str = r.get("scheduled_at")
            if sched_str:
                try:
                    s_dt = datetime.fromisoformat(sched_str)
                    if s_dt.tzinfo is None:
                        s_dt = s_dt.replace(tzinfo=IST)
                    if s_dt <= threshold_dt:
                        delay_hours = (now_dt - s_dt).total_seconds() / 3600.0
                        overdue.append({
                            "row_key": rk,
                            "day": r.get("day"),
                            "topic": r.get("topic"),
                            "scheduled_at": sched_str,
                            "delay_hours": round(delay_hours, 1),
                        })
                except Exception:
                    pass

    overdue.sort(key=lambda x: x["scheduled_at"])
    return overdue


def generate_watchdog_report(
    overdue_rows: list[dict],
    now: datetime | None = None,
    threshold_hours: float = 0.25,
) -> tuple[str, str]:
    """Generates (title, body) for watchdog GitHub Issue alert."""
    title = "Schedule overdue: rows not published"
    now_str = (now or datetime.now(IST)).strftime("%Y-%m-%d %H:%M IST")
    thresh_mins = int(threshold_hours * 60)

    lines = [
        f"### ⚠️ Schedule Watchdog Alert: Overdue Topics Detected",
        "",
        f"- **Inspection Time**: `{now_str}`",
        f"- **Overdue Topics Count**: `{len(overdue_rows)}`",
        f"- **Threshold**: `{threshold_hours} hrs` (~{thresh_mins} mins)",
        "",
        f"The following curriculum topics are more than {threshold_hours} hours past their scheduled publishing slot and remain in **Pending** status. This indicates that one or more scheduled GitHub Actions cron runs were dropped, delayed, or failed to trigger:",
        "",
        "| Row Key | Day | Scheduled Time | Overdue By | Topic |",
        "|:---:|:---:|:---:|:---:|:---|",
    ]

    for o in overdue_rows:
        lines.append(f"| `{o['row_key']}` | Day {o['day']} | `{o['scheduled_at']}` | ~{o['delay_hours']} hrs | **{o['topic']}** |")

    lines.extend([
        "",
        "#### 🛠️ Recommended Action:",
        "1. Check the GitHub Actions **Publish Finance Shorts** workflow run history for skipped or failed jobs.",
        "2. To manually trigger publication of the earliest overdue row, go to Actions > **Publish Finance Shorts** > **Run workflow** (select `mode: production`, `dry_run: false`).",
        "",
        "---",
        "*Automated alert generated by Finance Shorts Pro Watchdog.*",
    ])

    return (title, "\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser(description="Watchdog for overdue scheduled topics")
    parser.add_argument("--state-file", default=None, help="Path to schedule_state.json")
    parser.add_argument("--threshold-hours", type=float, default=0.25, help="Hours overdue threshold (default: 0.25h = 15m)")
    parser.add_argument("--out-title", default="watchdog_title.txt", help="Output title file")
    parser.add_argument("--out-body", default="watchdog_body.txt", help="Output body file")

    args = parser.parse_args()

    s_file = Path(args.state_file) if args.state_file else None
    overdue = find_overdue_rows(state_file=s_file, threshold_hours=args.threshold_hours)

    Path(args.out_title).write_text("", encoding="utf-8")
    Path(args.out_body).write_text("", encoding="utf-8")

    if overdue:
        print(f"[WARNING] Found {len(overdue)} overdue topics in schedule:")
        for o in overdue:
            print(f"  - [{o['row_key']}] '{o['topic']}' (overdue by {o['delay_hours']}h)")

        title, body = generate_watchdog_report(overdue, threshold_hours=args.threshold_hours)
        Path(args.out_title).write_text(title, encoding="utf-8")
        Path(args.out_body).write_text(body, encoding="utf-8")
        sys.exit(1)
    else:
        print("[OK] No overdue topics found in schedule.")
        sys.exit(0)


if __name__ == "__main__":
    main()
